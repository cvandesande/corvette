fn tokens(line: &str) -> Vec<&str> {
    line.split_whitespace().collect()
}

fn num<T: FromStr>(tok: &str, what: &str) -> Result<T, String>
where
    T::Err: Display,
{
    tok.parse::<T>().map_err(|e| format!("{what} '{tok}': {e}"))
}

fn parse_box(tok: &str) -> Result<[i32; 4], String> {
    let mut edges = [0_i32; 4];
    let mut filled = 0;
    for part in tok.split(',') {
        if filled >= 4 {
            return Err(format!("box '{tok}': too many edges"));
        }
        edges[filled] = num(part, "edge")?;
        filled += 1;
    }
    if filled != 4 {
        return Err(format!("box '{tok}': expected four edges"));
    }
    Ok(edges)
}

fn parse_centroid(tok: &str) -> Result<[i32; 2], String> {
    let mut parts = tok.split(',');
    let first = num(parts.next().unwrap_or(""), "centroid x")?;
    let second = num(parts.next().unwrap_or(""), "centroid y")?;
    if parts.next().is_some() {
        return Err(format!("centroid '{tok}': expected two values"));
    }
    Ok([first, second])
}

fn parse_region(tok: &str) -> Result<Vec<[i32; 4]>, String> {
    if tok == "-" {
        return Ok(Vec::new());
    }
    tok.split('/').map(parse_box).collect()
}

fn parse_scores(tok: &str) -> Result<Vec<f64>, String> {
    if tok == "-" {
        return Ok(Vec::new());
    }
    tok.split(',').map(|part| num(part, "score")).collect()
}

fn parse_bits(tok: &str) -> Result<([u64; 4], [u64; 4]), String> {
    if tok.len() != 128 {
        return Err(format!("bits '{tok}': expected 128 hex characters"));
    }
    let mut values = [0_u64; 8];
    for (slot, chunk) in values.iter_mut().zip(tok.as_bytes().chunks(16)) {
        let text = std::str::from_utf8(chunk).map_err(|e| format!("bits: {e}"))?;
        *slot = u64::from_str_radix(text, 16).map_err(|e| format!("bits '{text}': {e}"))?;
    }
    let velocity = [values[0], values[1], values[2], values[3]];
    let envelope = [values[4], values[5], values[6], values[7]];
    Ok((velocity, envelope))
}

fn parse_listed_boxes(line: &str) -> Result<Vec<[i32; 4]>, String> {
    if line == "-" {
        return Ok(Vec::new());
    }
    line.split_whitespace().map(parse_box).collect()
}

fn parse_triples(toks: &[&str]) -> Result<Vec<(Option<u64>, i64, bool)>, String> {
    if toks.len() == 1 && toks[0] == "-" {
        return Ok(Vec::new());
    }
    let mut rows = Vec::new();
    for tok in toks {
        let parts: Vec<&str> = tok.split(':').collect();
        if parts.len() != 3 {
            return Err(format!(
                "triple '{tok}': expected global_id:hit_counter:initializing"
            ));
        }
        let global_id = if parts[0] == "-" {
            None
        } else {
            Some(num(parts[0], "global id")?)
        };
        let hit_counter = num(parts[1], "hit counter")?;
        let initializing = match parts[2] {
            "0" => false,
            "1" => true,
            other => return Err(format!("initializing flag '{other}'")),
        };
        rows.push((global_id, hit_counter, initializing));
    }
    Ok(rows)
}

fn parse_object(toks: &[&str]) -> Result<ExpectedObject, String> {
    if toks.len() < 17 {
        return Err("short object line".to_owned());
    }
    let history_count: usize = num(toks[15], "history count")?;
    let expected_length = if history_count == 0 {
        19
    } else {
        18 + history_count
    };
    if toks.len() != expected_length {
        return Err(format!(
            "object line: history count {history_count} disagrees with the listed boxes"
        ));
    }
    let history: Vec<[i32; 4]> = if history_count == 0 {
        if toks[16] != "-" {
            return Err("object line: empty history must be -".to_owned());
        }
        Vec::new()
    } else {
        toks[16..16 + history_count]
            .iter()
            .map(|tok| parse_box(tok))
            .collect::<Result<_, _>>()?
    };
    let history_slots = history_count.max(1);
    let (velocity_bits, envelope_bits) = parse_bits(toks[17 + history_slots])?;
    Ok(ExpectedObject {
        idx: num(toks[1], "index")?,
        label: toks[2].to_owned(),
        score: num(toks[3], "score")?,
        edges: parse_box(toks[4])?,
        area: num(toks[5], "area")?,
        ratio: num(toks[6], "ratio")?,
        region: parse_region(toks[7])?,
        frame_time: num(toks[8], "frame time")?,
        centroid: parse_centroid(toks[9])?,
        estimate: parse_box(toks[10])?,
        start_time: num(toks[11], "start time")?,
        motionless: num(toks[12], "motionless")?,
        changes: num(toks[13], "changes")?,
        score_history: parse_scores(toks[14])?,
        history,
        disappeared: num(toks[16 + history_slots], "disappeared")?,
        velocity_bits,
        envelope_bits,
    })
}

fn parse_scenario(source: &str, lines: &[&str], start: usize) -> Result<(Scenario, usize), String> {
    let toks = tokens(lines[start]);
    if toks.len() != 17
        || toks[2] != "size"
        || toks[5] != "init"
        || toks[7] != "gone"
        || toks[9] != "after"
        || toks[11] != "defmax"
        || toks[13] != "max"
        || toks[15] != "own"
    {
        return Err(format!(
            "{source} line {}: malformed scenario line",
            start + 1
        ));
    }
    let width: i32 = num(toks[3], "width").map_err(|e| scenario_err(source, start, &e))?;
    let height: i32 = num(toks[4], "height").map_err(|e| scenario_err(source, start, &e))?;
    let min_initialized: u32 =
        num(toks[6], "min_initialized").map_err(|e| scenario_err(source, start, &e))?;
    let max_disappeared: u32 =
        num(toks[8], "max_disappeared").map_err(|e| scenario_err(source, start, &e))?;
    let after: u64 = num(toks[10], "after").map_err(|e| scenario_err(source, start, &e))?;
    let max_frames_default = if toks[12] == "none" {
        None
    } else {
        Some(num(toks[12], "default max frames").map_err(|e| scenario_err(source, start, &e))?)
    };
    let max_frames_overrides = if toks[14] == "none" {
        Vec::new()
    } else {
        toks[14]
            .split(',')
            .map(|pair| {
                let (label, value) = pair
                    .split_once('=')
                    .ok_or_else(|| format!("override '{pair}': expected label=value"))?;
                Ok((label.to_owned(), num(value, "max frames")?))
            })
            .collect::<Result<Vec<_>, String>>()
            .map_err(|e| scenario_err(source, start, &e))?
    };
    let own_labels = if toks[16] == "none" {
        Vec::new()
    } else {
        toks[16].split(',').map(str::to_owned).collect()
    };
    let (frames, next) =
        parse_frames(source, lines, start + 1).map_err(|e| scenario_err(source, start, &e))?;
    Ok((
        Scenario {
            name: toks[1].to_owned(),
            after,
            settings: TrackerSettings {
                width,
                height,
                min_initialized,
                max_disappeared,
                stationary_threshold: after,
                max_frames_default,
                max_frames_overrides,
                own_labels,
            },
            frames,
        },
        next,
    ))
}

fn scenario_err(source: &str, line: usize, detail: &str) -> String {
    format!("{source} line {}: {detail}", line + 1)
}

fn frame_err(source: &str, line: usize, detail: &str) -> String {
    format!("{source} line {}: {detail}", line + 1)
}

fn parse_frame_dets(
    source: &str,
    lines: &[&str],
    mut pos: usize,
    count: usize,
) -> Result<(Vec<FrameDetection>, usize), String> {
    let mut dets: Vec<FrameDetection> = Vec::new();
    for _offset in 0..count {
        pos += 1;
        if pos >= lines.len() {
            return Err(format!("{source}: missing detection line"));
        }
        let det = tokens(lines[pos]);
        if det.len() != 7 || det[0] != "D" {
            return Err(frame_err(source, pos, "expected a detection line"));
        }
        dets.push(FrameDetection {
            label: det[1].to_owned(),
            score: num(det[2], "score").map_err(|e| frame_err(source, pos, &e))?,
            edges: parse_box(det[3]).map_err(|e| frame_err(source, pos, &e))?,
            area: num(det[4], "area").map_err(|e| frame_err(source, pos, &e))?,
            ratio: num(det[5], "ratio").map_err(|e| frame_err(source, pos, &e))?,
            region: parse_region(det[6]).map_err(|e| frame_err(source, pos, &e))?,
        });
    }
    Ok((dets, pos))
}

fn parse_frames(
    source: &str,
    lines: &[&str],
    start: usize,
) -> Result<(Vec<ExpectedFrame>, usize), String> {
    let mut pos = start;
    let mut frames: Vec<ExpectedFrame> = Vec::new();
    loop {
        if pos >= lines.len() {
            return Err(format!("{source}: missing end"));
        }
        let toks = tokens(lines[pos]);
        let kind = toks.first().copied();
        if kind == Some("end") {
            return Ok((frames, pos + 1));
        }
        let from_frame_times = match kind {
            Some("d" | "t") => kind == Some("t"),
            _ => {
                return Err(frame_err(source, pos, "expected a frame line"));
            }
        };
        let time: f64 = num(toks.get(1).copied().unwrap_or(""), "frame time")
            .map_err(|e| frame_err(source, pos, &e))?;
        let dets = if from_frame_times {
            Vec::new()
        } else {
            let count: usize = num(toks.get(2).copied().unwrap_or(""), "detection count")
                .map_err(|e| frame_err(source, pos, &e))?;
            let (dets, next) = parse_frame_dets(source, lines, pos, count)?;
            pos = next;
            dets
        };
        pos += 1;
        let mut frame = ExpectedFrame {
            time,
            from_frame_times,
            dets,
            objects: Vec::new(),
            map: 0,
            untracked: Vec::new(),
            trackers: Vec::new(),
        };
        loop {
            if pos >= lines.len() {
                return Err(format!("{source}: missing frame result"));
            }
            let toks = tokens(lines[pos]);
            match toks.first().copied() {
                Some("d" | "t" | "end") => break,
                Some("o") => {
                    let object = parse_object(&toks).map_err(|e| frame_err(source, pos, &e))?;
                    frame.objects.push(object);
                    pos += 1;
                }
                Some("m") => {
                    frame.map = num(toks.get(1).copied().unwrap_or(""), "map count")
                        .map_err(|e| frame_err(source, pos, &e))?;
                    pos += 1;
                }
                Some("u") => {
                    let count: usize = num(toks.get(1).copied().unwrap_or(""), "untracked count")
                        .map_err(|e| frame_err(source, pos, &e))?;
                    pos += 1;
                    if pos >= lines.len() {
                        return Err(format!("{source}: missing untracked boxes line"));
                    }
                    frame.untracked =
                        parse_listed_boxes(lines[pos]).map_err(|e| frame_err(source, pos, &e))?;
                    if frame.untracked.len() != count {
                        return Err(frame_err(
                            source,
                            pos,
                            &format!("untracked count {count} disagrees with the listed boxes"),
                        ));
                    }
                    pos += 1;
                }
                Some("n") => {
                    let count: usize = num(toks.get(2).copied().unwrap_or(""), "tracker count")
                        .map_err(|e| frame_err(source, pos, &e))?;
                    let tracks =
                        parse_triples(&toks[3..]).map_err(|e| frame_err(source, pos, &e))?;
                    if tracks.len() != count {
                        return Err(frame_err(
                            source,
                            pos,
                            &format!("tracker count {count} disagrees with the listed tracks"),
                        ));
                    }
                    frame.trackers.push(TrackerState {
                        name: toks[1].to_owned(),
                        tracks,
                    });
                    pos += 1;
                }
                _ => {
                    return Err(frame_err(source, pos, "unknown result line"));
                }
            }
        }
        frames.push(frame);
    }
}

fn parse_rows(source: &str, text: &str) -> Result<Vec<Scenario>, String> {
    let lines: Vec<&str> = text.lines().collect();
    let mut scenarios = Vec::new();
    let mut pos = 0;
    while pos < lines.len() {
        if lines[pos].trim().is_empty() || lines[pos].starts_with('#') {
            pos += 1;
            continue;
        }
        if !lines[pos].starts_with("s ") {
            return Err(format!(
                "{source} line {}: expected a scenario line",
                pos + 1
            ));
        }
        let (scenario, next) = parse_scenario(source, &lines, pos)?;
        scenarios.push(scenario);
        pos = next;
    }
    Ok(scenarios)
}

fn counts_from_header(text: &str) -> Result<BTreeMap<String, u64>, String> {
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("# counts ") {
            let toks: Vec<&str> = rest.split_whitespace().collect();
            let mut map = BTreeMap::new();
            for pair in toks.chunks(2) {
                if pair.len() != 2 {
                    return Err("counts header: expected name value pairs".to_owned());
                }
                map.insert(pair[0].to_owned(), num(pair[1], "count")?);
            }
            return Ok(map);
        }
    }
    Err("counts header missing".to_owned())
}

const fn bits_of(value: f64) -> u64 {
    value.to_bits()
}

fn compare_object(where_for: &str, view: &ObjectView, expected: &ExpectedObject) {
    assert_eq!(expected.label, view.label, "{where_for}: label");
    assert_eq!(
        bits_of(expected.score),
        bits_of(view.score),
        "{where_for}: score"
    );
    assert_eq!(expected.edges, view.edges, "{where_for}: box");
    assert_eq!(expected.area, view.area, "{where_for}: area");
    assert_eq!(
        bits_of(expected.ratio),
        bits_of(view.ratio),
        "{where_for}: ratio"
    );
    assert_eq!(
        expected.region.as_slice(),
        view.region,
        "{where_for}: region"
    );
    assert_eq!(
        bits_of(expected.frame_time),
        bits_of(view.frame_time),
        "{where_for}: frame time"
    );
    assert_eq!(expected.centroid, view.centroid, "{where_for}: centroid");
    assert_eq!(expected.estimate, view.estimate, "{where_for}: estimate");
    assert_eq!(
        bits_of(expected.start_time),
        bits_of(view.start_time),
        "{where_for}: start time"
    );
    assert_eq!(
        expected.motionless, view.motionless,
        "{where_for}: motionless"
    );
    assert_eq!(
        expected.changes, view.position_changes,
        "{where_for}: changes"
    );
    assert_eq!(
        expected
            .score_history
            .iter()
            .map(|value| bits_of(*value))
            .collect::<Vec<_>>(),
        view.score_history
            .iter()
            .map(|value| bits_of(*value))
            .collect::<Vec<_>>(),
        "{where_for}: score history"
    );
    for edge in 0..4 {
        assert_eq!(
            expected.envelope_bits[edge],
            bits_of(view.envelope[edge]),
            "{where_for}: envelope edge {edge}"
        );
        assert_eq!(
            expected.velocity_bits[edge],
            bits_of(view.estimate_velocity[edge]),
            "{where_for}: velocity {edge}"
        );
    }
    assert_eq!(
        expected.history.as_slice(),
        view.history,
        "{where_for}: history"
    );
    assert_eq!(
        expected.disappeared, view.disappeared,
        "{where_for}: disappeared"
    );
}

fn replay(source: &str, scenario: &Scenario, ids: &mut IdSource) {
    let mut tracker = ObjectTracker::new(scenario.settings.clone(), ids).unwrap();
    for (frame_number, frame) in scenario.frames.iter().enumerate() {
        if frame.from_frame_times {
            tracker.update_frame_times(frame.time).unwrap();
        } else {
            tracker
                .match_and_update(frame.time, frame.dets.clone())
                .unwrap();
        }
        let where_for = format!("{source} scenario {} frame {}", scenario.name, frame_number);
        let views: Vec<_> = tracker.objects().collect();
        assert_eq!(
            views.len(),
            frame.objects.len(),
            "{where_for}: object count"
        );
        let mut previous_idx: Option<usize> = None;
        for (view, expected) in views.iter().zip(&frame.objects) {
            if let Some(previous) = previous_idx {
                assert!(previous < expected.idx, "{where_for}: registration order");
            }
            previous_idx = Some(expected.idx);
            compare_object(&where_for, view, expected);
        }
        assert_eq!(
            tracker.map_entries(),
            frame.map,
            "{where_for}: track id map"
        );
        assert_eq!(
            tracker.untracked_boxes(),
            frame.untracked.as_slice(),
            "{where_for}: untracked boxes"
        );
        assert_eq!(
            tracker.tracker_states(),
            frame.trackers,
            "{where_for}: tracker state"
        );
    }
}

