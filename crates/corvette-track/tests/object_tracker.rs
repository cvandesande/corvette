#[test]
fn fixture_counts_match_a_recomputation_from_the_rows() {
    let scenarios = parse_rows("fixture", FIXTURE).unwrap();
    let declared = counts_from_header(FIXTURE).unwrap();
    let mut recomputed: BTreeMap<String, u64> = BTreeMap::new();
    recomputed.insert("scenarios".to_owned(), scenarios.len() as u64);
    let mut frames = 0_u64;
    let mut registered = 0_u64;
    let mut retired = 0_u64;
    let mut frames_disappeared = 0_u64;
    let mut frames_untracked = 0_u64;
    let mut threshold_crossings = 0_u64;
    let mut time_only = 0_u64;
    for scenario in &scenarios {
        let mut highest_index = 0_u64;
        let mut seen: BTreeMap<usize, u64> = BTreeMap::new();
        let mut present_last: BTreeMap<usize, u64> = BTreeMap::new();
        for frame in &scenario.frames {
            frames += 1;
            time_only += u64::from(frame.from_frame_times);
            if frame.objects.iter().any(|object| object.disappeared > 0) {
                frames_disappeared += 1;
            }
            if !frame.untracked.is_empty() {
                frames_untracked += 1;
            }
            present_last.clear();
            for object in &frame.objects {
                highest_index = highest_index.max(object.idx as u64 + 1);
                let previous = seen.get(&object.idx).copied().unwrap_or(0);
                if previous < scenario.after && object.motionless >= scenario.after {
                    threshold_crossings += 1;
                }
                seen.insert(object.idx, object.motionless);
                present_last.insert(object.idx, 0);
            }
        }
        registered += highest_index;
        retired += highest_index - u64::try_from(present_last.len()).unwrap();
    }
    recomputed.insert("frames".to_owned(), frames);
    recomputed.insert("registered".to_owned(), registered);
    recomputed.insert("frames_disappeared".to_owned(), frames_disappeared);
    recomputed.insert("frames_untracked".to_owned(), frames_untracked);
    recomputed.insert("threshold_crossings".to_owned(), threshold_crossings);
    recomputed.insert("time_only_frames".to_owned(), time_only);
    for (name, value) in &recomputed {
        assert_eq!(
            declared.get(name),
            Some(value),
            "fixture counts {name} disagrees with the parsed rows"
        );
        assert!(*value >= 40, "recomputed {name} below 40");
    }
    assert_eq!(
        retired,
        declared.get("retire_max_frames").copied().unwrap()
            + declared.get("retire_expiry").copied().unwrap(),
        "retirements split by cause"
    );
    assert!(
        declared.get("retire_max_frames").copied().unwrap_or(0) >= 40,
        "retire_max_frames floor"
    );
    assert!(
        declared.get("retire_expiry").copied().unwrap_or(0) >= 40,
        "retire_expiry floor"
    );
    assert!(
        declared.get("retire_with_sibling").copied().unwrap_or(0) >= 40,
        "retire_with_sibling floor"
    );
}

