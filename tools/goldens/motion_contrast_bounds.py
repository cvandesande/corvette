import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[2] / "crates/corvette-motion/tests/fixtures/contrast_bounds_cases.txt"

SEEDED_SIZES = [
    (122, 100),
    (133, 100),
    (81, 100),
    (100, 122),
    (64, 48),
    (7, 5),
    (5, 7),
    (13, 1),
    (1, 13),
    (2, 2),
    (3, 3),
    (1, 2),
    (2, 1),
    (1, 1),
]

SEEDED_RANGES = [(0, 256), (10, 100), (100, 2), (200, 56), (0, 1), (30, 3)]

SPLIT_SIZES = [(122, 100), (133, 100), (81, 100), (64, 48), (20, 20)]

SPLIT_LEVELS = [(0, 255), (10, 200), (100, 125), (0, 25), (50, 75), (13, 38), (200, 255), (5, 6)]

BRANCH_LOWER_LEVELS = (0, 1, 7, 13, 50, 100, 128, 200)


def lcg_bytes(seed: int, count: int) -> bytes:
    state = seed
    out = bytearray(count)
    for i in range(count):
        state = (state * 1664525 + 1013904223) % (1 << 32)
        out[i] = state >> 24
    return bytes(out)


def bounds(resized_frame):
    min_value = np.percentile(resized_frame, 4).astype(np.uint8)
    max_value = np.percentile(resized_frame, 96).astype(np.uint8)
    return int(min_value), int(max_value)


def record(kind: str, picture, fields) -> str:
    lower, upper = bounds(picture)
    assert isinstance(lower, int) and isinstance(upper, int)
    assert 0 <= lower <= 255 and 0 <= upper <= 255
    head = " ".join(str(field) for field in fields)
    return f"{kind} {head} {lower} {upper}"


def explicit_pictures():
    ys, xs = np.indices((8, 8))
    checkerboard = np.where((xs + ys) % 2 == 0, 255, 0).astype(np.uint8)
    return [
        np.array([[200]], dtype=np.uint8),
        np.array([[7, 9]], dtype=np.uint8),
        np.array([[9, 7]], dtype=np.uint8),
        np.array([[0, 100, 255]], dtype=np.uint8),
        np.array([[0], [255]], dtype=np.uint8),
        np.full((5, 5), 77, dtype=np.uint8),
        np.tile(np.arange(256, dtype=np.uint8), (4, 1)),
        np.tile(np.arange(256, dtype=np.uint8).reshape(256, 1), (1, 4)),
        checkerboard,
        np.arange(99, -1, -1, dtype=np.uint8).reshape(10, 10),
        np.array([[5] * 12 + [200]], dtype=np.uint8),
        np.array([[0, 0, 0], [0, 255, 255], [255, 255, 128]], dtype=np.uint8),
    ]


def main() -> None:
    lines = []
    seeded_lines = []
    for (sw, sh) in SEEDED_SIZES:
        for (lo, span) in SEEDED_RANGES:
            seed = 301 + len(seeded_lines)
            raw = np.frombuffer(lcg_bytes(seed, sw * sh), dtype=np.uint8).reshape(sh, sw)
            picture = (raw.astype(np.int64) % span + lo).astype(np.uint8)
            seeded_lines.append(record("seeded", picture, (sw, sh, seed, lo, span)))
    assert len(seeded_lines) == 84 and seeded_lines[0].split()[3] == "301"

    split_lines = []
    for (sw, sh) in SPLIT_SIZES:
        n = sw * sh
        p4 = (n - 1) * 4 // 100
        p96 = (n - 1) * 96 // 100
        ks = list(range(p4 - 2, p4 + 4)) + list(range(p96 - 2, p96 + 4))
        for (lo, hi) in SPLIT_LEVELS:
            for k in ks:
                picture = np.full((sh, sw), hi, dtype=np.uint8)
                picture.ravel()[:k] = lo
                split_lines.append(record("split", picture, (sw, sh, k, lo, hi)))
    assert len(split_lines) == 480

    explicit_lines = []
    for picture in explicit_pictures():
        sh, sw = picture.shape
        explicit_lines.append(record("explicit", picture, (sw, sh, picture.tobytes().hex())))
    assert len(explicit_lines) == 12

    branch_lines = []
    high_gamma = 0
    for n in range(2, 65):
        for p in (4, 96):
            virtual = float(n - 1) * (p / 100.0)
            k = math.floor(virtual)
            gamma = virtual - float(k)
            found = None
            for a in BRANCH_LOWER_LEVELS:
                for b in range(a + 1, 256):
                    diff = float(b) - float(a)
                    lower = math.floor(float(a) + diff * gamma)
                    upper = math.floor(float(b) - diff * (1.0 - gamma))
                    if lower != upper:
                        found = (a, b, lower, upper)
                        break
                if found is not None:
                    break
            if found is None:
                continue
            a, b, lower, upper = found
            picture = np.array([[a] * (k + 1) + [b] * (n - k - 1)], dtype=np.uint8)
            picked = upper if gamma >= 0.5 else lower
            numpy_bound = bounds(picture)[0 if p == 4 else 1]
            assert numpy_bound == picked, (n, p, a, b, lower, upper, numpy_bound)
            if gamma >= 0.5:
                high_gamma += 1
            branch_lines.append(record("branch", picture, (n, 1, picture.tobytes().hex())))
    assert len(branch_lines) == 15 and high_gamma == 7 and len(branch_lines) - high_gamma == 8

    lines.append(f"counts {len(seeded_lines)} {len(split_lines)} {len(explicit_lines)} {len(branch_lines)}")
    lines.extend(seeded_lines)
    lines.extend(split_lines)
    lines.extend(explicit_lines)
    lines.extend(branch_lines)
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")


main()
